import assert from 'node:assert/strict';
import {dailySelection} from '../src/data/dailySelection';
import {deduplicateDailyEvents} from '../src/data/dailyEditorial';
import {manualDailyItems,withManualDaily} from '../src/data/manualDaily';
const now=new Date('2026-10-29T20:00:00Z');
const story=(title,date,sourceId='news-koreadaily')=>({title,date,sourceId,url:'https://example.com/'+encodeURIComponent(title),summary:'',firstPublishedEdition:'2026-10-29'});
const first=story('美 3분기 GDP 3.2% 성장 전망','2026-10-29T11:26:00Z','news-koreatownpress');
const rows=[story('미국 3분기 GDP 3.4% 깜짝 성장 AI가 끌고','2026-10-29T12:53:35Z'),first,story('미국 3분기 GDP 3.4% AI 투자 소비 호조','2026-10-29T12:53:00Z')];
assert.deepEqual(deduplicateDailyEvents(rows),[first]);
assert.equal(deduplicateDailyEvents([...rows,story('미국 2분기 GDP 성장','2026-10-29T12:00:00Z'),story('한국 3분기 GDP 성장','2026-10-29T12:00:00Z')]).length,3);
const old=story('한인 생활 안내','2026-10-29T03:00:00Z');
const fresh=story('LA 생활 안내','2026-10-29T18:00:00Z');
assert.deepEqual(dailySelection([old,fresh],now,true).items.map(x=>x.title),[fresh.title,old.title]);
const full=Array.from({length:45},(_,i)=>story('한인 소식 '+i,'2026-10-29T18:00:00Z'));
const result=dailySelection(withManualDaily([...full,...rows], '2026-10-29'),now,true).items;
assert.equal(result.length,40);
for(const item of manualDailyItems)assert(result.some(x=>x.url===item.url));
assert.equal(result.at(-1).url,'https://www.koreatimes.com/article/1634388');
assert.equal(withManualDaily([], '2026-10-30').length,0);
console.log('PASS: earliest GDP winner, distinct quarters/countries, date-first order, all three additions within cap, original dates, expiry.');
