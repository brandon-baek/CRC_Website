export type Locale = 'en' | 'ko';

export const locales: Locale[] = ['en', 'ko'];

/** Prefix a site-relative path for the given locale. `path` starts with '/'. */
export function localePath(locale: Locale, path: string): string {
  return locale === 'en' ? path : `/ko${path === '/' ? '/' : path}`;
}

/** The same page in the other language (used by the header toggle). */
export function otherLocalePath(locale: Locale, path: string): string {
  return localePath(locale === 'en' ? 'ko' : 'en', path);
}

